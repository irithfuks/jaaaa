// Fast lookup index mapping unvoweled target words
const supplementaryUnvoweledMap = new Map<string, SupplementaryWordEntry>();
Object.values(SUPPLEMENTARY_HEBREW_WORDS).forEach(entry => {
  supplementaryUnvoweledMap.set(stripHebrewNiqqud(entry.targetWord), entry);
});

export function getSupplementaryEntry(targetWord: string): SupplementaryWordEntry | undefined {
  if (!targetWord) return undefined;
  if (SUPPLEMENTARY_HEBREW_WORDS[targetWord]) {
    return SUPPLEMENTARY_HEBREW_WORDS[targetWord];
  }
  const clean = stripHebrewNiqqud(targetWord);
  return supplementaryUnvoweledMap.get(clean);
}

